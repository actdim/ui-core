import { scales, parseTheme } from './parseTheme.ts';
import type { ParsedTheme } from './parseTheme.ts';

export interface TokenModuleNames {
    tokens: string;
    vars: string;
    utilities: string;
    variants: string;
    header: string;
}

export function quote(value: string): string {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\s+/g, ' ')}'`;
}

export function renderRecord(record: Record<string, string>): string {
    const entries = Object.entries(record).map(([k, v]) => `${quote(k)}: ${quote(v)}`);

    return `{ ${entries.join(', ')} }`;
}

export function renderTokenModule(
    theme: ParsedTheme,
    names: TokenModuleNames,
    options?: { allScales?: boolean },
): string {
    const allScales = options?.allScales ?? true;
    const lines: string[] = [];
    lines.push(names.header);
    lines.push('');
    lines.push(`export const ${names.tokens} = {`);
    for (const scale of scales) {
        const scaleTokens = theme.tokens[scale.key] || {};
        const entries = Object.entries(scaleTokens);
        if (!allScales && entries.length === 0) {
            continue;
        }
        if (entries.length === 0) {
            lines.push(`    ${scale.key}: {},`);
            continue;
        }
        lines.push(`    ${scale.key}: {`);
        for (const [name, token] of entries) {
            const parts = [`var: ${quote(token.var)}`, `value: ${quote(token.value)}`];
            if (Object.keys(token.modes).length > 0) {
                parts.push(`modes: ${renderRecord(token.modes)}`);
            }
            if (Object.keys(token.props).length > 0) {
                parts.push(`props: ${renderRecord(token.props)}`);
            }
            lines.push(`        ${quote(name)}: { ${parts.join(', ')} },`);
        }
        lines.push('    },');
    }
    lines.push('} as const;');
    lines.push('');
    lines.push(`export const ${names.vars} = {`);
    for (const scale of scales) {
        const scaleTokens = theme.tokens[scale.key] || {};
        const entries = Object.entries(scaleTokens);
        if (!allScales && entries.length === 0) {
            continue;
        }
        if (entries.length === 0) {
            lines.push(`    ${scale.key}: {},`);
            continue;
        }
        lines.push(`    ${scale.key}: {`);
        for (const [name, token] of entries) {
            lines.push(`        ${quote(name)}: ${quote(token.var)},`);
        }
        lines.push('    },');
    }
    lines.push('} as const;');
    lines.push('');
    lines.push(`export const ${names.utilities} = [${theme.utilities.map(quote).join(', ')}] as const;`);
    lines.push('');
    lines.push(`export const ${names.variants} = [${theme.variants.map(quote).join(', ')}] as const;`);
    lines.push('');

    return lines.join('\n');
}

export function renderThemeTokens(css: string): string {
    const theme = parseTheme(css);

    return renderTokenModule(
        theme,
        {
            tokens: 'themeTokens',
            vars: 'themeCssVars',
            utilities: 'themeUtilities',
            variants: 'themeVariants',
            header: '// GENERATED by postcss.ts (pnpm theme:gen) from src/theme/theme.css. Do not edit.',
        },
        { allScales: false },
    );
}
