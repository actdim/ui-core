import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import { parseTheme, modeFromSelector } from './parseTheme.ts';
import { renderThemeTokens, renderTokenModule } from './renderTheme.ts';

function findUiCorePackageRoot(startDir: string): string {
    let cur = path.resolve(startDir);
    while (true) {
        const pkgPath = path.join(cur, 'package.json');
        if (fs.existsSync(pkgPath)) {
            try {
                const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
                if (pkg.name === '@actdim/ui-core') {
                    return cur;
                }
            } catch {
                // ignore
            }
        }
        const parent = path.dirname(cur);
        if (parent === cur) {
            return path.resolve(startDir);
        }
        cur = parent;
    }
}

const uiCoreRoot = findUiCorePackageRoot(path.dirname(fileURLToPath(import.meta.url)));

export const coreThemeCssFile = path.join(uiCoreRoot, 'src', 'theme', 'theme.css');
export const coreThemeGeneratedFile = path.join(uiCoreRoot, 'src', 'theme', 'theme.generated.ts');

export function generateThemeTokens(
    cssFile: string = coreThemeCssFile,
    outFile: string = coreThemeGeneratedFile,
): boolean {
    const output = renderThemeTokens(fs.readFileSync(cssFile, 'utf8'));
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : undefined;
    if (current === output) {
        return false;
    }
    const outDir = path.dirname(outFile);
    if (!fs.existsSync(outDir)) {
        fs.mkdirSync(outDir, { recursive: true });
    }
    fs.writeFileSync(outFile, output, 'utf8');

    return true;
}

export interface AppThemeOptions {
    appCssFile: string;
    outFile: string;
    baseCssFile?: string; // default coreThemeCssFile
    exportName?: string; // default 'appThemeTokens'
    allowCoreOverrides?: boolean; // default false
}

export function renderAppThemeTokens(options: AppThemeOptions): string {
    const baseCssFile = options.baseCssFile || coreThemeCssFile;
    const baseCss = fs.readFileSync(baseCssFile, 'utf8');
    const baseTheme = parseTheme(baseCss);

    const baseVars = new Set<string>();
    for (const scale of Object.values(baseTheme.tokens)) {
        for (const token of Object.values(scale)) {
            baseVars.add(token.var);
        }
    }

    const appCss = fs.readFileSync(options.appCssFile, 'utf8');
    const basename = path.basename(options.appCssFile);
    const allowCoreOverrides = Boolean(options.allowCoreOverrides);

    if (!allowCoreOverrides) {
        const appRoot = postcss.parse(appCss);
        appRoot.walkAtRules('theme', (atRule) => {
            atRule.walkDecls((decl) => {
                if (baseVars.has(decl.prop)) {
                    throw new Error(`${basename}: ${decl.prop} redeclares a core token (allowCoreOverrides is off)`);
                }
            });
        });

        appRoot.walkRules((rule) => {
            const mode = modeFromSelector(rule.selector);
            if (!mode) {
                return;
            }
            rule.each((node) => {
                if (node.type === 'decl' && baseVars.has(node.prop)) {
                    throw new Error(
                        `${basename}: ${node.prop} overrides a core token in ${rule.selector} (allowCoreOverrides is off)`,
                    );
                }
            });
        });
    }

    const appTheme = parseTheme(appCss, allowCoreOverrides ? baseTheme : undefined);

    const relPath = path.relative(path.dirname(options.outFile), options.appCssFile).replace(/\\/g, '/');
    const header = `// GENERATED by @actdim/ui-core/theme-tooling from ${relPath}. Do not edit.`;

    return renderTokenModule(
        appTheme,
        {
            tokens: options.exportName || 'appThemeTokens',
            vars: 'appThemeCssVars',
            utilities: 'appThemeUtilities',
            variants: 'appThemeVariants',
            header,
        },
        { allScales: true },
    );
}

export function generateAppThemeTokens(options: AppThemeOptions): boolean {
    const output = renderAppThemeTokens(options);
    const current = fs.existsSync(options.outFile) ? fs.readFileSync(options.outFile, 'utf8') : undefined;
    if (current === output) {
        return false;
    }
    const outDir = path.dirname(options.outFile);
    if (!fs.existsSync(outDir)) {
        fs.mkdirSync(outDir, { recursive: true });
    }
    fs.writeFileSync(options.outFile, output, 'utf8');

    return true;
}
