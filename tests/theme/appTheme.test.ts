import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import {
    generateAppThemeTokens,
    renderAppThemeTokens,
    scales,
} from '../../src/theme/tooling/index.ts';

describe('app theme generator', () => {
    it('generates app tokens with every scale key present and empty ones as {}', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-theme-'));
        const appCssFile = path.join(dir, 'app-theme.css');
        const outFile = path.join(dir, 'app-theme.generated.ts');

        const appCss = `
@theme static {
    --color-reader-sepia-surface: #f4ebd0;
    --spacing-reader-gutter: 1.5rem;
}
.dark {
    --color-reader-sepia-surface: #2d241e;
}
`;
        fs.writeFileSync(appCssFile, appCss, 'utf8');

        try {
            const output = renderAppThemeTokens({ appCssFile, outFile });
            expect(output).toContain('// GENERATED by @actdim/ui-core/theme-tooling from app-theme.css. Do not edit.');
            expect(output).toContain('export const appThemeTokens = {');
            expect(output).toContain('export const appThemeCssVars = {');
            expect(output).toContain("'reader-sepia-surface': { var: '--color-reader-sepia-surface', value: '#f4ebd0', modes: { 'dark': '#2d241e' } }");
            expect(output).toContain("'reader-gutter': { var: '--spacing-reader-gutter', value: '1.5rem' }");

            // Verify every scale key is present
            for (const scale of scales) {
                expect(output).toContain(`    ${scale.key}:`);
            }
            // An empty scale is {}
            expect(output).toContain('    container: {},');
            expect(output).toContain('    radius: {},');
        } finally {
            fs.rmSync(dir, { recursive: true, force: true });
        }
    });

    it('rejects redeclaring a core token when allowCoreOverrides is off', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-theme-'));
        const appCssFile = path.join(dir, 'app-theme.css');
        const outFile = path.join(dir, 'app-theme.generated.ts');

        const appCss = `
@theme static {
    --color-primary: #123456;
}
`;
        fs.writeFileSync(appCssFile, appCss, 'utf8');

        try {
            expect(() => renderAppThemeTokens({ appCssFile, outFile })).toThrowError(
                'app-theme.css: --color-primary redeclares a core token (allowCoreOverrides is off)',
            );
        } finally {
            fs.rmSync(dir, { recursive: true, force: true });
        }
    });

    it('accepts redeclaring a core token when allowCoreOverrides is true', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-theme-'));
        const appCssFile = path.join(dir, 'app-theme.css');
        const outFile = path.join(dir, 'app-theme.generated.ts');

        const appCss = `
@theme static {
    --color-primary: #123456;
}
`;
        fs.writeFileSync(appCssFile, appCss, 'utf8');

        try {
            const output = renderAppThemeTokens({ appCssFile, outFile, allowCoreOverrides: true });
            expect(output).toContain("'primary': { var: '--color-primary', value: '#123456' }");
        } finally {
            fs.rmSync(dir, { recursive: true, force: true });
        }
    });

    it('rejects mode override of a core token when allowCoreOverrides is off', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-theme-'));
        const appCssFile = path.join(dir, 'app-theme.css');
        const outFile = path.join(dir, 'app-theme.generated.ts');

        const appCss = `
@theme static {
    --color-custom-app: #111111;
}
.dark {
    --color-primary: #000000;
}
`;
        fs.writeFileSync(appCssFile, appCss, 'utf8');

        try {
            expect(() => renderAppThemeTokens({ appCssFile, outFile })).toThrowError(
                'app-theme.css: --color-primary overrides a core token in .dark (allowCoreOverrides is off)',
            );
        } finally {
            fs.rmSync(dir, { recursive: true, force: true });
        }
    });

    it('writes only when the output changes (idempotent write)', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-theme-'));
        const appCssFile = path.join(dir, 'app-theme.css');
        const outFile = path.join(dir, 'app-theme.generated.ts');

        const appCss = `
@theme static {
    --color-custom-app: #111111;
}
`;
        fs.writeFileSync(appCssFile, appCss, 'utf8');

        try {
            expect(generateAppThemeTokens({ appCssFile, outFile })).toBe(true);
            expect(generateAppThemeTokens({ appCssFile, outFile })).toBe(false);
            expect(fs.readFileSync(outFile, 'utf8')).toContain("'custom-app': { var: '--color-custom-app'");
        } finally {
            fs.rmSync(dir, { recursive: true, force: true });
        }
    });
});
